COLORS = {0: BG, 1: BLUE, 2: WHITE, 3: YELLOW, 4: DARK, 5: PINK, 6: BLUSH, 7: EAR_TINT}


def make_png(width, height, pixels):
    """Create PNG bytes from RGBA pixel data."""
    # PNG signature
    sig = b'\x89PNG\r\n\x1a\n'

    # IHDR chunk
    ihdr_data = struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0)  # 8bit RGBA
    ihdr = make_chunk(b'IHDR', ihdr_data)

    # IDAT chunk - raw image data with zlib compression
    raw = b''
    for y in range(height):
        raw += b'\x00'  # filter byte
        sy = y * 32 // height
        for x in range(width):
            sx = x * 32 // width
            r, g, b, a = COLORS[grid[sy][sx]]
            raw += struct.pack('BBBB', r, g, b, a)

    compressed = zlib.compress(raw)
    idat = make_chunk(b'IDAT', compressed)

    # IEND chunk
    iend = make_chunk(b'IEND', b'')

    return sig + ihdr + idat + iend


def make_chunk(chunk_type, data):
    """Create a PNG chunk."""
    length = struct.pack('>I', len(data))
    crc = struct.pack('>I', zlib.crc32(chunk_type + data) & 0xffffffff)
    return length + chunk_type + data + crc


